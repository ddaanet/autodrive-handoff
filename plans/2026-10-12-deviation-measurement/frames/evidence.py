#!/usr/bin/env python3
"""Write evidence.md: one entry per counted deviation, verbatim.

usage: evidence.py <frames-dir>

The file holds text from private repositories and stays outside any repository.
"""
import csv, os, sys
base = sys.argv[1]
tsv = lambda n: list(csv.DictReader(open(os.path.join(base, n)), delimiter="\t"))
hits = tsv("hits.tsv")
frames = {(f["repo"], f["blob"]): f for f in tsv("frames.tsv")}
samp = {r["id"]: r for r in tsv("sample.tsv")}
out = open(os.path.join(base, "evidence.md"), "w", encoding="utf-8")
w = out.write
w("# Handoff frame adherence: evidence\n\n"
  "Generated by `evidence.py` from `hits.tsv`, `sample.tsv` and `my-labels.tsv`.\n"
  "Holds verbatim text from private repositories: not for any repository.\n\n"
  "Entry: repository | path | commit or working copy | date | class | excerpt.\n"
  "Rule dates and class definitions are in `frames.py` and `my-labels.tsv`.\n\n"
  "## 1. Mechanical deviations (rule in force when the version was written)\n")
dev = [h for h in hits if h["in_force"] == "1"]
for cls in sorted({h["class"] for h in dev}):
    rows = [h for h in dev if h["class"] == cls]
    w(f"\n### {cls} ({len(rows)})\n\n")
    for h in sorted(rows, key=lambda h: (h["kind"], h["repo"], h["date"])):
        w(f"- {h['repo']} | {h['path']} | {h['commit']} | {h['date']} | {cls} | "
          f"{h['excerpt']}\n")
w("\n## 2. Hits against a rule not yet in force (would fail today, not deviations)\n\n"
  "Counts only; the rows are in `hits.tsv` with `in_force` 0.\n\n")
from collections import Counter
for (k, c), n in sorted(Counter((h["kind"], h["class"]) for h in hits
                                if h["in_force"] == "0").items()):
    w(f"- {k} {c}: {n}\n")
w("\n## 3. Commit-status candidates and their verdicts\n\n"
  "`commit-candidates.tsv` holds every sentence the filter matched with its hand\n"
  "verdict; `commit-verdicts.tsv` defines the verdicts.\n")
w("\n## 4. Judgement classes, read by hand (stratified sample)\n")
labels = {}
for line in open(os.path.join(base, "my-labels.tsv"), encoding="utf-8"):
    if line.startswith("#") or not line.strip():
        continue
    p = line.rstrip("\n").split("\t")
    labels[p[0]] = (p[1], p[2] if len(p) > 2 else "")
for sid, (lab, note) in labels.items():
    s = samp[sid]
    f = frames[(s["repo"], s["blob"])]
    fn = [x for x in os.listdir(os.path.join(base, "blobs", s["repo"]))
          if x.startswith(s["blob"])][0]
    text = open(os.path.join(base, "blobs", s["repo"], fn), encoding="utf-8",
                errors="replace").read().strip()
    w(f"\n### {sid}: {lab}\n\n{s['repo']} | {f['paths']} | {f['commit']} | {s['date']} | "
      f"{lab} | {note}\n\n")
    if lab != "OK":
        body = text if len(text) <= 2500 else text[:2500] + "\n[... cut at 2500 of " + str(len(text)) + " characters]"
        w("```\n" + body.replace("```", "'''") + "\n```\n")
w("\n## 5. Judgement classes, prior labelling\n\n"
  "`prior-labels.tsv` has the per-version unit counts; the per-unit labels are\n"
  "`plans/2026-10-11-task-and-todo-move-to-root/reports/overflow/labels.tsv` in the\n"
  "handoff repository, which holds no frame text.\n")
out.close()
print(len(dev), "mechanical deviations;", sum(1 for v in labels.values() if v[0] != "OK"),
      "judged deviating of", len(labels))
